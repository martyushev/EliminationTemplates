import numpy as np

def coefs_wpnp_2x2sym(data):

    A = data[0].T.flat
    B = data[1].T.flat

    C = np.zeros((4,16),dtype=complex)
    C.flat[[8,19,39,53]] = 64*A[2]**2
    C.flat[[15,28]] = -8*A[2]*B[4]+8*1j*A[2]*B[5]
    C.flat[[46,61]] = -8*1j*A[2]*B[5]-8*A[2]*B[4]
    C.flat[62] = -8*A[0]*B[0]+8*A[1]*B[3]-8*1j*A[0]*B[1]-8*1j*A[1]*B[2]
    C.flat[31] = 8*A[0]*B[0]+8*A[1]*B[3]-8*1j*A[0]*B[1]+8*1j*A[1]*B[2]
    C.flat[45] = 8*1j*A[0]*B[1]-8*1j*A[1]*B[2]+8*A[0]*B[0]+8*A[1]*B[3]
    C.flat[12] = 8*1j*A[0]*B[1]+8*1j*A[1]*B[2]-8*A[0]*B[0]+8*A[1]*B[3]
    C.flat[[1,25,32,59]] = -32*A[0]**2+32*A[1]**2
    C.flat[[4,22,42,50]] = 32*A[0]**2+32*A[1]**2

    C = C/np.linalg.norm(C,axis=1,keepdims=True)

    def U(s):
        return np.array([s[1]*s[2]*s[0]**2,s[1]*s[0]*s[2]**2,s[1]*s[3]*s[0]**2,s[0]*s[1]*s[2]*s[3],s[0]*s[1]*s[3]**2,s[0]*s[1]*s[2],s[1]*s[2]**2,s[0]*s[1]*s[3],s[3]*s[2]*s[1],s[1]*s[3]**2,s[1]*s[2],s[1]*s[3],s[0],s[2],s[3],1])

    def dU(s):
        return np.column_stack([[2*s[0]*s[1]*s[2],s[1]*s[2]**2,2*s[0]*s[1]*s[3],s[3]*s[2]*s[1],s[1]*s[3]**2,s[1]*s[2],0,s[1]*s[3],0,0,0,0,1,0,0,0],[s[2]*s[0]**2,s[0]*s[2]**2,s[3]*s[0]**2,s[0]*s[2]*s[3],s[0]*s[3]**2,s[0]*s[2],s[2]**2,s[0]*s[3],s[2]*s[3],s[3]**2,s[2],s[3],0,0,0,0],[s[1]*s[0]**2,2*s[0]*s[1]*s[2],0,s[0]*s[1]*s[3],0,s[1]*s[0],2*s[1]*s[2],0,s[1]*s[3],0,s[1],0,0,1,0,0],[0,0,s[1]*s[0]**2,s[0]*s[1]*s[2],2*s[0]*s[1]*s[3],0,0,s[1]*s[0],s[1]*s[2],2*s[1]*s[3],0,s[1],0,0,1,0]])

    return C,U,dU