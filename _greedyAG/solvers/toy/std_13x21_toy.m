    [L,~,Pi] = lu(M(:,1:10));
    Pi = Pi';
    M = [Pi*L Pi(:,11:end)]\M(:,11:end);
    M = M(end-2:end,:);

    T = zeros(8);
    T(1:3,:) = -M(:,1:3)\M(:,4:end);
