function coefs_wpnp_2x2sym(data)

    A = data[1]
    B = data[2]

    C = zeros(ComplexF64,4,16)

    C[[14,24,31,33]] .= 64*A[3]^2
    C[[56,59]] .= -8*A[3]*B[5]-8*im*A[3]*B[6]
    C[[50,61]] .= 8*im*A[3]*B[6]-8*A[3]*B[5]
    C[60] = -8*A[1]*B[1]+8*A[2]*B[4]-8*im*A[1]*B[2]-8*im*A[2]*B[3]
    C[55] = 8*A[1]*B[1]+8*A[2]*B[4]+8*im*A[1]*B[2]-8*im*A[2]*B[3]
    C[62] = -8*im*A[1]*B[2]+8*im*A[2]*B[3]+8*A[1]*B[1]+8*A[2]*B[4]
    C[49] = 8*im*A[1]*B[2]+8*im*A[2]*B[3]-8*A[1]*B[1]+8*A[2]*B[4]
    C[[3,5,38,48]] .= -32*A[1]^2+32*A[2]^2
    C[[12,17,26,43]] .= 32*A[1]^2+32*A[2]^2

    C = C./norm.(eachrow(C))

    U(s) = [s[2]*s[3]*s[1]^2,s[2]*s[1]*s[3]^2,s[2]*s[4]*s[1]^2,s[1]*s[2]*s[3]*s[4],s[1]*s[2]*s[4]^2,s[1]*s[2]*s[3],s[2]*s[3]^2,s[1]*s[2]*s[4],s[3]*s[2]*s[4],s[2]*s[4]^2,s[2]*s[3],s[2]*s[4],s[1],s[3],s[4],1];
    dU(s) = [[2*s[1]*s[2]*s[3],s[2]*s[3]^2,2*s[1]*s[2]*s[4],s[3]*s[2]*s[4],s[2]*s[4]^2,s[2]*s[3],0,s[2]*s[4],0,0,0,0,1,0,0,0] [s[3]*s[1]^2,s[1]*s[3]^2,s[1]^2*s[4],s[1]*s[3]*s[4],s[1]*s[4]^2,s[1]*s[3],s[3]^2,s[1]*s[4],s[3]*s[4],s[4]^2,s[3],s[4],0,0,0,0] [s[2]*s[1]^2,2*s[1]*s[2]*s[3],0,s[1]*s[2]*s[4],0,s[2]*s[1],2*s[2]*s[3],0,s[2]*s[4],0,s[2],0,0,1,0,0] [0,0,s[2]*s[1]^2,s[1]*s[2]*s[3],2*s[1]*s[2]*s[4],0,0,s[2]*s[1],s[2]*s[3],2*s[2]*s[4],0,s[2],0,0,1,0]];

    return C,U,dU

end