function coefs_toa2d_33(data)

    dd = data[1]

    C = zeros(3,10)

    C[[1,2,3]] .= -2
    C[19] = -2*dd[1]
    C[20] = -2*dd[2]
    C[21] = -2*dd[3]
    C[10] = -2*dd[4]
    C[11] = -2*dd[5]
    C[12] = -2*dd[6]
    C[4] = -2*dd[7]
    C[5] = -2*dd[8]
    C[6] = -2*dd[9]
    C[17] = 2*dd[2]+2*dd[5]
    C[14] = 2*dd[2]+2*dd[8]
    C[18] = 2*dd[3]+2*dd[6]
    C[15] = 2*dd[3]+2*dd[9]
    C[16] = 2*dd[4]+2*dd[1]
    C[9] = 2*dd[6]+2*dd[9]
    C[13] = 2*dd[7]+2*dd[1]
    C[7] = 2*dd[7]+2*dd[4]
    C[8] = 2*dd[8]+2*dd[5]
    C[22] = -2*dd[1]*dd[4]+2*dd[1]*dd[7]+2*dd[4]*dd[7]-2*dd[7]^2
    C[25] = 2*dd[1]*dd[4]-2*dd[1]*dd[7]-2*dd[4]^2+2*dd[4]*dd[7]
    C[28] = -2*dd[1]^2+2*dd[1]*dd[4]+2*dd[1]*dd[7]-2*dd[4]*dd[7]
    C[23] = -2*dd[2]*dd[5]+2*dd[2]*dd[8]+2*dd[5]*dd[8]-2*dd[8]^2
    C[26] = 2*dd[2]*dd[5]-2*dd[2]*dd[8]-2*dd[5]^2+2*dd[5]*dd[8]
    C[29] = -2*dd[2]^2+2*dd[2]*dd[5]+2*dd[2]*dd[8]-2*dd[5]*dd[8]
    C[24] = -2*dd[3]*dd[6]+2*dd[3]*dd[9]+2*dd[6]*dd[9]-2*dd[9]^2
    C[27] = 2*dd[3]*dd[6]-2*dd[3]*dd[9]-2*dd[6]^2+2*dd[6]*dd[9]
    C[30] = -2*dd[3]^2+2*dd[3]*dd[6]+2*dd[3]*dd[9]-2*dd[6]*dd[9]

    C = C./norm.(eachrow(C))

    U(s) = [s[1]*s[2]*s[3],s[1]^2,s[2]*s[1],s[2]^2,s[1]*s[3],s[2]*s[3],s[3]^2,s[1],s[2],s[3]];
    dU(s) = [[s[2]*s[3],2*s[1],s[2],0,s[3],0,0,1,0,0] [s[1]*s[3],0,s[1],2*s[2],0,s[3],0,0,1,0] [s[2]*s[1],0,0,0,s[1],s[2],2*s[3],0,0,1]];

    return C,U,dU

end